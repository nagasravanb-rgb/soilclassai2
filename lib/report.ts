import { SOURCE_LABELS, type AnalysisResult } from "./schema";

const ESCAPES: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
export function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, ch => ESCAPES[ch]);
}

function list(items: string[], empty = "None provided."): string {
  if (!items.length) return `<p class="muted">${escapeHtml(empty)}</p>`;
  return `<ul>${items.map(i => `<li>${escapeHtml(i)}</li>`).join("")}</ul>`;
}

function formatDate(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toUTCString();
}

const SAFE_IMAGE = /^data:image\/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$/;

/** Builds a standalone, printable HTML report. All dynamic values are HTML-escaped. */
export function renderReportHtml(result: AnalysisResult, imageDataUrl?: string | null): string {
  const r = result;
  const pct = Math.round(r.classification.confidence * 100);
  const image = imageDataUrl && SAFE_IMAGE.test(imageDataUrl)
    ? `<img src="${imageDataUrl}" alt="Analyzed soil sample" class="sample" />`
    : "";
  const obs = r.observations;
  const obsRows = ([
    ["Colour", obs.color],
    ["Texture", obs.texture],
    ["Particles", obs.particles],
    ["Stones / debris", obs.stonesDebris],
    ["Organic matter indicators", obs.organicMatter],
  ] as const)
    .map(([k, v]) => `<tr><th>${k}</th><td>${escapeHtml(v.value)}</td><td>${SOURCE_LABELS[v.source]}</td></tr>`)
    .join("");
  const props = r.properties
    .map(p => `<tr><th>${escapeHtml(p.name)}</th><td>${escapeHtml(p.assessment)}</td><td>${SOURCE_LABELS[p.source]}</td></tr>`)
    .join("");
  const nutrients = r.nutrients
    .map(n => `<tr><th>${escapeHtml(n.name)}</th><td>${escapeHtml(n.status)}</td><td>${escapeHtml(n.note)}</td></tr>`)
    .join("");
  const rec = r.recommendations;
  const tests = r.suggestedTests.map(t => `<li><strong>${escapeHtml(t.name)}</strong> — ${escapeHtml(t.reason)}</li>`).join("");
  const mockBanner = r.provider.isMock
    ? `<p class="mock">DEMO RESULT — generated by the mock provider for testing. This is NOT a real AI analysis of the image.</p>`
    : "";

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" />
<title>SoilClass AI report — ${escapeHtml(r.city)} — ${escapeHtml(r.createdAt.slice(0, 10))}</title>
<style>
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#1d2a22;max-width:860px;margin:24px auto;padding:0 16px;line-height:1.5}
h1{color:#25553a;margin-bottom:4px}h2{color:#25553a;border-bottom:1px solid #d8e4d9;padding-bottom:4px;margin-top:28px}
table{border-collapse:collapse;width:100%}th,td{text-align:left;vertical-align:top;padding:6px 8px;border-bottom:1px solid #e5ece5}th{width:30%}
.muted{color:#5d6b61}.sample{max-width:320px;max-height:320px;border-radius:8px;border:1px solid #d8e4d9}
.mock{background:#fff3cd;border:1px solid #e0c36b;padding:10px;font-weight:700}.note{background:#f4f8f3;border:1px solid #d8e4d9;padding:10px;border-radius:6px}
@media print{body{margin:0}a{color:inherit}}
</style></head><body>
<h1>SoilClass AI — Soil photo analysis report</h1>
<p class="muted">Analysis ID ${escapeHtml(r.id)} · ${escapeHtml(formatDate(r.createdAt))} · City: ${escapeHtml(r.city)} · Provider: ${escapeHtml(r.provider.name)} (${escapeHtml(r.provider.model)})</p>
${mockBanner}
${image}
<h2>Summary</h2><p>${escapeHtml(r.summary)}</p>
<h2>Predicted soil category (AI prediction)</h2>
<p><strong>${escapeHtml(r.classification.label)}</strong> — model confidence ${pct}% (${r.classification.confidenceLevel}). Confidence is the model's own estimate, not scientific certainty.</p>
${r.classification.alternatives.length ? `<p class="muted">Alternatives: ${r.classification.alternatives.map(a => `${escapeHtml(a.label)} (${Math.round(a.confidence * 100)}%)`).join(", ")}</p>` : ""}
<h3>Visual evidence</h3>${list(r.classification.evidence)}
<h2>Visual observations</h2><table><tbody>${obsRows}</tbody></table>${list(obs.additional, "")}
<h2>Estimated moisture condition</h2><p><strong>${escapeHtml(r.moisture.label)}</strong> (AI visual estimate). ${escapeHtml(r.moisture.evidence)}</p><p class="muted">${escapeHtml(r.moisture.note)}</p>
<h2>Soil properties (estimated)</h2>${props ? `<table><tbody>${props}</tbody></table>` : `<p class="muted">None provided.</p>`}
<h3>Possible limitations</h3>${list(r.limitations)}
<h2>Nutrients and chemical properties</h2><p class="note">No nutrient or chemical values were measured. A photograph cannot determine these.</p><table><tbody>${nutrients}</tbody></table>
<h2>Agricultural guidance (general — not based on measured soil data)</h2>
<h3>Soil management</h3>${list(rec.soilManagement)}<h3>Organic matter</h3>${list(rec.organicMatter)}
<h3>Water management</h3>${list(rec.waterManagement)}<h3>Drainage</h3>${list(rec.drainage)}<h3>Nutrient education</h3>${list(rec.nutrientEducation)}
<h2>Suggested follow-up tests</h2><ul>${tests}</ul>
<h2>Uncertainty</h2>${list(r.uncertainty)}
<h2>City context</h2><p>${escapeHtml(r.cityContext.note)}</p>
<h2>Scientific limitations</h2>${list(r.scientificLimitations)}
${r.removedClaims ? `<p class="muted">${r.removedClaims} AI statement(s) containing unsupported numeric measurements were removed.</p>` : ""}
<p class="muted">Generated by SoilClass AI. Verify important agricultural decisions with a laboratory soil test and qualified local advice.</p>
</body></html>`;
}

export function reportFileName(result: AnalysisResult): string {
  const city = result.city.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "soil";
  return `soilclass-report-${city}-${result.createdAt.slice(0, 10)}.html`;
}
